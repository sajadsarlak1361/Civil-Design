import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { saveDwg } from './dwgEngine';
import { readDwgLibre } from './dwgLibre';
import { mapDwgDatabase } from './dwgMap';

describe('DWG mapping', () => {
  it('maps layers, geometry, blocks, and xrefs', () => {
    const imported = mapDwgDatabase(
      {
        entities: [
          { type: 'LINE', layer: 'Road', colorIndex: 1, lineweight: 25, lineType: 'Continuous', startPoint: { x: 1, y: 2, z: 3 }, endPoint: { x: 4, y: 5, z: 6 } },
          { type: 'LWPOLYLINE', layer: 'Road', flag: 1, elevation: 1, vertices: [{ x: 0, y: 0, bulge: 0 }, { x: 2, y: 0, bulge: 0.5 }, { x: 2, y: 2, bulge: 0 }] },
          { type: 'POLYLINE3D', layer: 'Road', flag: 8, vertices: [{ x: 0, y: 0, z: 1 }, { x: 3, y: 0, z: 2 }, { x: 3, y: 3, z: 3 }] },
          { type: 'ARC', layer: '0', center: { x: 0, y: 0, z: 0 }, radius: 3, startAngle: 0, endAngle: Math.PI / 2 },
          { type: 'CIRCLE', layer: '0', center: { x: 2, y: 2, z: 0 }, radius: 4 },
          { type: 'TEXT', layer: '0', startPoint: { x: 1, y: 1, z: 0 }, textHeight: 2.5, rotation: 0, text: 'STA' },
          { type: 'MTEXT', layer: '0', insertionPoint: { x: 1, y: 2, z: 0 }, textHeight: 1, text: 'A\\PB' },
          { type: 'POINT', layer: 'Road', position: { x: 8, y: 9, z: 1 } },
          { type: '3DFACE', layer: 'TIN', corner1: { x: 0, y: 0, z: 1 }, corner2: { x: 1, y: 0, z: 1 }, corner3: { x: 0, y: 1, z: 2 } },
          { type: 'INSERT', layer: '0', name: 'Mark', insertionPoint: { x: 10, y: 11, z: 0 }, xScale: 2, yScale: 2, zScale: 1, rotation: 0 },
          { type: 'INSERT', layer: '0', name: 'Survey', insertionPoint: { x: 20, y: 21, z: 0 }, xScale: 1, yScale: 1, zScale: 1, rotation: 0 },
        ],
        tables: {
          LAYER: { entries: [{ name: 'Road', colorIndex: 1, lineType: 'Continuous', lineweight: 25, locked: true, frozen: false, off: false }] },
          BLOCK_RECORD: {
            entries: [
              { name: 'Mark', flags: 0, basePoint: { x: 0, y: 0, z: 0 }, entities: [{ type: 'LINE', layer: 'Road', startPoint: { x: 0, y: 0, z: 0 }, endPoint: { x: 2, y: 0, z: 0 } }] },
              { name: 'Survey', flags: 4, basePoint: { x: 0, y: 0, z: 0 }, entities: [{ type: 'LINE', layer: 'Road', startPoint: { x: 0, y: 0, z: 0 }, endPoint: { x: 5, y: 1, z: 0 } }] },
            ],
          },
        },
      },
      'AC1015',
    );
    const line = imported.entities.find((entity) => entity.type === 'line' && entity.layer === 'Road');
    expect(line).toMatchObject({ a: { x: 1, y: 2, z: 3 }, b: { x: 4, y: 5, z: 6 }, lineweight: 25 });
    expect(imported.layers[0]).toMatchObject({ name: 'Road', locked: true, colorIndex: 1 });
    expect(imported.entities.some((entity) => entity.type === 'polyline' && entity.poly3d)).toBe(true);
    expect(imported.entities.some((entity) => entity.type === 'text' && entity.content === 'STA')).toBe(true);
    expect(imported.entities.some((entity) => entity.type === 'text' && entity.content === 'A\nB')).toBe(true);
    expect(imported.entities.filter((entity) => entity.type === 'line' && entity.layer === 'TIN')).toHaveLength(3);
    const mark = imported.entities.find((entity) => entity.type === 'block' && entity.name === 'Mark');
    expect(mark).toMatchObject({ p: { x: 10, y: 11, z: 0 }, scale: 2, xref: false });
    expect(imported.entities.some((entity) => entity.type === 'line' && entity.a.x === 10 && entity.b.x === 14)).toBe(true);
    expect(imported.xrefs[0]).toMatchObject({ name: 'Survey', overlay: false, referenced: true, insertion: { x: 20, y: 21, z: 0 } });
    expect(imported.xrefs[0].entities[0]).toMatchObject({ type: 'line', b: { x: 25, y: 22, z: 0 } });
    expect(imported.notes.join(' ')).toMatch(/AC1015/);
  });
});

describe('LibreDWG sample', () => {
  it('reads the DWG generated by LibreDWG', async () => {
    const bytes = readFileSync(resolve('src/engine/formats/fixtures/entities.dwg'));
    const imported = await readDwgLibre(bytes);
    const line = imported.entities.find((entity) => entity.type === 'line');
    expect(line && line.type === 'line' && line.a.x).toBeCloseTo(1, 3);
    expect(line && line.type === 'line' && line.b).toMatchObject({ x: 4, y: 5, z: 6 });
    expect(imported.entities.some((entity) => entity.type === 'circle' && Math.abs(entity.radius - 4) < 1e-3)).toBe(true);
    expect(imported.entities.some((entity) => entity.type === 'arc')).toBe(true);
    expect(imported.entities.some((entity) => entity.type === 'text' && entity.content.includes('STA'))).toBe(true);
    expect(imported.entities.some((entity) => entity.type === 'point')).toBe(true);
    expect(imported.entities.some((entity) => entity.type === 'polyline')).toBe(true);
    expect(imported.entities.some((entity) => entity.type === 'block')).toBe(true);
    expect(imported.layers.some((layer) => layer.name.toLowerCase() === 'road')).toBe(true);
  });
});

describe('browser DWG save', () => {
  it('writes a DXF when ODA File Converter is not available', async () => {
    const saved = await saveDwg({ entities: [], faces: [], layers: [] }, 'm');
    expect(saved.extension).toBe('dxf');
    expect(new TextDecoder().decode(saved.bytes)).toContain('SECTION');
    expect(saved.note).toContain('DXF');
  });
});
