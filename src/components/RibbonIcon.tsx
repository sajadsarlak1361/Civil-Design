function keyFor(command: string): string {
  const name = command.toUpperCase();
  if (PATHS[name]) return name;
  if (name.startsWith('CIRCLE')) return 'CIRCLE';
  if (name.startsWith('ARC')) return 'ARC';
  if (name.startsWith('ELLIPSE')) return 'ELLIPSE';
  if (name.startsWith('RECT')) return 'RECTANG';
  if (name.startsWith('SPLINE')) return 'SPLINE';
  if (name.startsWith('DIM')) return 'DIM';
  if (name.startsWith('MLEADER')) return 'MLEADER';
  if (name.startsWith('ARRAY')) return 'ARRAYRECT';
  if (name.startsWith('ZOOM')) return 'ZOOM';
  return 'DEFAULT';
}

export function RibbonIcon({ command, large = false }: { command: string; large?: boolean }) {
  return (
    <svg viewBox="0 0 24 24" aria-hidden="true" className={large ? 'icon-lg' : 'icon-sm'}>
      <path d={PATHS[keyFor(command)]} />
    </svg>
  );
}
